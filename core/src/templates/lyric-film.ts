/**
 * Lyric motion, the film: a planned program (lyric-video.ts) as Pocket Motion
 * nodes and baked keyframes.
 *
 * - Every cut is gated in time (shown when its transition starts, hidden when
 *   the next cut covers it) and nests: ground → shapes → decorative text →
 *   an exit wrapper → a hold wrapper (drift, float, breathe, jitter) → the
 *   chromatic ghost passes and the entrance (per glyph, per plate, or a wipe
 *   or slices of the whole block) → the glyphs; then notes, a flash, the
 *   signature.
 * - Koma-uchi: a style with `koma` 12 has every motion sampled at 12
 *   drawings a second and held between them (pairs of keyframes, linear);
 *   the engine has no steps() easing. Delays snap to the same 1/12 s grid,
 *   so everything on screen changes on the same frames.
 * - Beat: ghosts spike and decor pulses once per beat of the style's tempo.
 * - Type plates are images: this module places them (type-raster.ts
 *   geometry) and lists them; composeLyrics draws the pixels.
 * - Textures (grain, scanlines, paper, vignette) lie over everything; their
 *   images are generated by lyric-texture.ts.
 */
